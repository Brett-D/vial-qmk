"""Generate rgb_layout.c (RGB Matrix layout for the Keyhive Sofle v2).

    python gen_rgb_layout.py                 # built-in (derived) default map
    python gen_rgb_layout.py --map led.json  # bake a map measured with the
                                             # page's LED calibration wizard

led.json is the wizard's "Copy result" JSON: {"leds": [...74 entries...]},
entry i = physical LED i (0-36 left chain, 37-73 right chain) as "row,col",
"underglow" or "none".

Without --map the default is derived from keyhive's rgblight led_map applied
to the Sofle RGB chain order in keyboards/sofle/info.json (known to be wrong
on Brett's board; measure it with the wizard).
"""
import argparse
import json
from pathlib import Path

from paths import write, LEDS, QMK_ROOT as ROOT
ROWS, COLS, LEDS = 10, 7, 74
UNDERGLOW, NONE = 0xFE, 0xFF
W, H = 16.5, 5.75  # layout size in key units -> QMK's 224 x 64 LED space


def keyhive():
    return json.loads((ROOT / "keyboards/sofle/keyhive/keyboard.json").read_text())


def key_positions(kh):
    pos = {}
    for k in kh["layouts"]["LAYOUT"]["layout"]:
        r, c = k["matrix"]
        pos[(r, c)] = (round((k["x"] + 0.5) * 224 / W), round((k["y"] + k.get("h", 1) / 2) * 64 / H))
    return pos


def derived_map(kh):
    sofle = json.loads((ROOT / "keyboards/sofle/info.json").read_text())
    rev1 = json.loads((ROOT / "keyboards/sofle/rev1/keyboard.json").read_text())
    pos_rev1 = {tuple(k["matrix"]): (k["x"], k["y"]) for k in rev1["layouts"]["LAYOUT"]["layout"]}
    by_pos = {(k["x"], k["y"]): tuple(k["matrix"]) for k in kh["layouts"]["LAYOUT"]["layout"]}
    logical = []
    for half in range(2):
        for e in sofle["rgb_matrix"]["layout"][half * 36:(half + 1) * 36]:
            logical.append(by_pos[pos_rev1[tuple(e["matrix"])]] if "matrix" in e else None)
        logical.append((4, 0) if half == 0 else (9, 5))
    codes = [None] * LEDS
    for i, p in enumerate(kh["rgblight"]["led_map"]):
        codes[p] = UNDERGLOW if logical[i] is None else logical[i][0] * COLS + logical[i][1]
    return codes


def measured_map(path):
    leds = json.loads(Path(path).read_text())["leds"]
    assert len(leds) == LEDS, f"expected {LEDS} entries, got {len(leds)}"
    codes = []
    for e in leds:
        if e == "underglow":
            codes.append(UNDERGLOW)
        elif e in ("none", None):
            codes.append(NONE)
        else:
            r, c = map(int, e.split(","))
            codes.append(r * COLS + c)
    return codes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--map", help="measured LED map JSON from the calibration wizard")
    args = ap.parse_args()
    kh = keyhive()
    pos = key_positions(kh)
    codes = measured_map(args.map) if args.map else derived_map(kh)
    keys = [c for c in codes if c < ROWS * COLS]
    assert len(keys) == len(set(keys)), "a key is assigned to two LEDs"

    co = [["NO_LED"] * COLS for _ in range(ROWS)]
    pts, flags = [], []
    for i, c in enumerate(codes):
        if c < ROWS * COLS:
            co[c // COLS][c % COLS] = str(i)
            pts.append(pos[(c // COLS, c % COLS)])
            flags.append("LED_FLAG_KEYLIGHT")
        else:
            pts.append(None)
            flags.append("LED_FLAG_UNDERGLOW" if c == UNDERGLOW else "LED_FLAG_NONE")
    for i in range(LEDS):  # non-key LEDs: between their nearest key LEDs on the chain
        if pts[i] is None:
            lo, hi = (0, 37) if i < 37 else (37, LEDS)
            nb = []
            for d in range(1, 37):
                nb = [pts[j] for j in (i - d, i + d) if lo <= j < hi and codes[j] < ROWS * COLS]
                if nb:
                    break
            pts[i] = (round(sum(p[0] for p in nb) / len(nb)), round(sum(p[1] for p in nb) / len(nb))) if nb else (56 if i < 37 else 168, 32)

    src = "measured with the config page's LED calibration wizard (%s)" % Path(args.map).name if args.map else \
        "derived from keyhive's rgblight led_map + the Sofle RGB chain order (unverified)"
    out = [
        "// Copyright 2026 Brett-D",
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "//",
        "// Generated by tools/gen.py rgb-layout (tools/gen_rgb_layout.py) - do not edit.",
        "//",
        "// RGB Matrix layout for the Keyhive Sofle v2: 37 LEDs per half in physical",
        "// chain order (0-36 left, 37-73 right). Built-in map: " + src + ".",
        "// A map measured with the calibration wizard and saved on the keyboard",
        "// replaces it at runtime (led_map.c).",
        "",
        '#include "quantum.h"',
        "",
        "#ifdef RGB_MATRIX_ENABLE",
        '_Static_assert(RGB_MATRIX_LED_COUNT == %d, "rgb_layout.c has %d LEDs");' % (LEDS, LEDS),
        "",
        "// clang-format off",
        "#define LED_CONFIG_DEFAULT { { \\",
    ]
    for r in range(ROWS):
        out.append("    { " + ", ".join("%6s" % x for x in co[r]) + " }, \\")
    out.append("}, { \\")
    for i in range(0, LEDS, 8):
        out.append("    " + " ".join("{%3d,%3d}," % p for p in pts[i:i + 8]) + " \\")
    out.append("}, { \\")
    for i in range(0, LEDS, 6):
        out.append("    " + " ".join(f + "," for f in flags[i:i + 6]) + " \\")
    out += ["} }", "",
            "const led_config_t led_config_default = LED_CONFIG_DEFAULT;",
            "led_config_t       g_led_config       = LED_CONFIG_DEFAULT;",
            "",
            "// Centre of each key in LED space (for runtime maps).",
            "const uint8_t key_led_pos[MATRIX_ROWS][MATRIX_COLS][2] = {"]
    for r in range(ROWS):
        out.append("    { " + ", ".join("{%3d,%3d}" % pos.get((r, c), (0, 0)) for c in range(COLS)) + " },")
    out += ["};", "// clang-format on", "#endif", ""]
    write(LEDS / "rgb_layout.c", "\n".join(out))
    print(f"rgb_layout.c: {len(keys)} key LEDs, {codes.count(UNDERGLOW)} underglow, {codes.count(NONE)} none ({src})")


if __name__ == "__main__":
    main()
