"""Pixel art for the OLED pet ("Pip", an original little antenna blob).

Writes ../pet_art.h (bitmaps for the right OLED) and pet_art.json (the same
sprites for the config page's preview), so the two never drift apart.

    python gen_pet_art.py            (stdlib only; run after editing the art)
"""
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
W = H = 24


def grid():
    return [[0] * W for _ in range(H)]


def body(g, antenna=True, halo=False):
    cx, cy, rx, ry = 11.5, 14.0, 10.6, 8.6
    inside = lambda x, y: ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1.0
    for y in range(H):
        for x in range(W):
            if inside(x, y) and not all(inside(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                g[y][x] = 1
    for x in (7, 8, 15, 16):  # feet
        g[23][x] = 1
    if antenna:
        for x, y in ((12, 5), (12, 4), (13, 3), (13, 2), (14, 1), (15, 1), (14, 0), (15, 0)):
            g[y][x] = 1
    if halo:
        for x in range(8, 16):
            g[0][x] = g[3][x] = 1
        g[1][7] = g[2][7] = g[1][16] = g[2][16] = 1


def put(g, pts, v=1):
    for x, y in pts:
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = v


def rect(x0, y0, x1, y1):
    return [(x, y) for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)]


EYES_OPEN = rect(7, 10, 8, 12) + rect(15, 10, 16, 12)
SMILE = [(10, 16), (11, 17), (12, 17), (13, 16)]

FACES = {
    "idle": EYES_OPEN + SMILE,
    "blink": rect(7, 12, 8, 12) + rect(15, 12, 16, 12) + SMILE,
    "happy": [(6, 12), (7, 11), (8, 11), (9, 12), (14, 12), (15, 11), (16, 11), (17, 12)]
    + [(9, 15), (14, 15)] + rect(10, 15, 13, 15) + [(10, 16), (13, 16)] + rect(11, 17, 12, 17) + [(11, 16), (12, 16)],
    "sad": rect(7, 11, 8, 12) + rect(15, 11, 16, 12) + [(6, 10), (7, 9), (16, 9), (17, 10)]
    + [(10, 17), (11, 16), (12, 16), (13, 17), (18, 13), (18, 14)],
    "tired": rect(7, 12, 8, 12) + rect(15, 12, 16, 12) + rect(6, 11, 9, 11) + rect(14, 11, 17, 11) + rect(10, 17, 13, 17),
    "sleep": [(6, 11), (7, 12), (8, 12), (9, 11), (14, 11), (15, 12), (16, 12), (17, 11), (11, 16), (12, 16), (11, 17), (12, 17)],
    "eat": EYES_OPEN + [(10, 15), (11, 14), (12, 14), (13, 15), (9, 16), (14, 16), (10, 17), (13, 17), (11, 18), (12, 18)] + rect(10, 16, 13, 16) + rect(11, 15, 12, 17),
    "dead": [(6, 10), (8, 10), (7, 11), (6, 12), (8, 12), (15, 10), (17, 10), (16, 11), (15, 12), (17, 12)] + rect(10, 17, 13, 17),
}


def sprite(face):
    g = grid()
    if face == "egg":
        cx, cy = 11.5, 13.0
        for y in range(H):
            for x in range(W):
                r = ((x - cx) / 8.0) ** 2 + ((y - cy) / (10.5 if y < cy else 9.0)) ** 2
                if r <= 1.0 and r > 0.72:
                    g[y][x] = 1
        put(g, [(7, 9), (8, 9), (15, 15), (16, 15), (16, 16), (9, 18), (10, 18)])  # spots
        put(g, [(4, 13), (6, 12), (8, 13), (10, 12), (12, 13), (14, 12), (16, 13), (18, 12)])  # crack
        return g
    body(g, antenna=face != "dead", halo=face == "dead")
    put(g, FACES[face])
    return g


SPRITES = ["idle", "blink", "happy", "sad", "tired", "sleep", "eat", "dead", "egg"]

ICONS = {  # 8x8
    "heart": ["........", ".##.##..", "#######.", "#######.", ".#####..", "..###...", "...#....", "........"],
    "z": ["........", ".#####..", "....#...", "...#....", "..#.....", ".#####..", "........", "........"],
    "apple": ["....#...", "...#.##.", ".##.##..", "#######.", "#######.", "#######.", ".#####..", "..#.#..."],
    "ball": ["..###...", ".#.#.#..", "#..#..#.", "#######.", "#..#..#.", ".#.#.#..", "..###...", "........"],
    "moon": ["..###...", ".##.....", "##......", "##......", "##......", ".##...#.", "..####..", "........"],
    "sparkle": ["...#....", "...#....", ".#.#.#..", "..###...", "#######.", "..###...", ".#.#.#..", "...#...."],
    "poop": ["...#....", "..##....", ".####...", ".#..#...", "######..", "#.##.##.", "########", "........"],
    "no": ["#.....#.", ".#...#..", "..#.#...", "...#....", "..#.#...", ".#...#..", "#.....#.", "........"],
    "egg": ["..###...", ".#...#..", "#.#...#.", "#.....#.", "#..#..#.", "#.....#.", ".#####..", "........"],
}
STAT_ICONS = {  # 5x5: food, joy, energy, clean
    "food": [".#.#.", "#####", "#####", "#####", ".###."],
    "joy": ["##.##", "#####", "#####", ".###.", "..#.."],
    "energy": ["..##.", ".##..", "#####", "..##.", ".##.."],
    "clean": ["..#..", ".###.", "#####", "#####", ".###."],
}


def ascii(g):
    return ["".join("#" if v else "." for v in row) for row in g]


def main():
    art = {s: ascii(sprite(s)) for s in SPRITES}
    for name, rows in list(ICONS.items()) + list(STAT_ICONS.items()):
        n = len(rows[0])
        assert len(rows) == n and all(len(r) == n for r in rows), name
    lines = [
        "// Generated by config_page/gen_pet_art.py - edit the art there.",
        "// Pip, the OLED pet: original pixel art.",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "enum { " + ", ".join(f"PET_SPR_{s.upper()}" for s in SPRITES) + ", PET_SPR_COUNT };",
        "enum { " + ", ".join(f"PET_ICON_{s.upper()}" for s in ICONS) + ", PET_ICON_COUNT };",
        "",
        "// 24x24 sprites: one row per uint32_t, bit 23 = leftmost pixel.",
        "static const uint32_t pet_sprites[PET_SPR_COUNT][24] = {",
    ]
    for s in SPRITES:
        lines.append(f"    {{ // {s}")
        for row in art[s]:
            lines.append(f"        0x{int(row.replace('#', '1').replace('.', '0'), 2):06X}, // {row}")
        lines.append("    },")
    lines += ["};", "", "// 8x8 icons: bit 7 = leftmost pixel.", "static const uint8_t pet_icons[PET_ICON_COUNT][8] = {"]
    for name, rows in ICONS.items():
        lines.append("    {" + ", ".join(f"0x{int(r.replace('#', '1').replace('.', '0'), 2):02X}" for r in rows) + f"}}, // {name}")
    lines += ["};", "", "// 5x5 stat icons (food, joy, energy, clean): bit 4 = leftmost pixel.", "static const uint8_t pet_stat_icons[4][5] = {"]
    for name, rows in STAT_ICONS.items():
        lines.append("    {" + ", ".join(f"0x{int(r.replace('#', '1').replace('.', '0'), 2):02X}" for r in rows) + f"}}, // {name}")
    lines += ["};", ""]
    (HERE.parent / "pet_art.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    (HERE / "pet_art.json").write_text(json.dumps({"sprites": art, "icons": ICONS, "stats": STAT_ICONS}, separators=(",", ":")), encoding="utf-8", newline="\n")
    for s in SPRITES:
        print(f"--- {s}")
        print("\n".join(art[s]))


if __name__ == "__main__":
    main()
