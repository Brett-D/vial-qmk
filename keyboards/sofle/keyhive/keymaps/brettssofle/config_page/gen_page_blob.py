"""Build the copy of the config page the keyboard delivers by typing.

Reads sofle-config.html and bootstrap.html (this folder) and writes
../config_page_blob.h:

  config_page_gz[]         the page, minified and gzipped (typed as base32)
  config_bootstrap_keys[]  the bootstrap data: URL as US-layout HID usages
                           (| 0x80 = with Shift), typed into the address bar

Run by rules.mk at every build (the header is only rewritten when it
changes) and by gen_config.py, so the delivered page never drifts from
sofle-config.html. Standard library only.

    python gen_page_blob.py [--print-url]
"""

import gzip
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "config_page_blob.h"

# Report rates used for the time estimate (deliver.c).
BOOT_REPORT_MS = 3   # address bar: key down + key up per character
STREAM_REPORT_MS = 1  # page: one report per symbol (USB polls every 1 ms)


def css_min(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"\s*([{};:,>])\s*", r"\1", s)
    return s.replace(";}", "}").strip()


def js_min(s):
    # Conservative: drop indentation, blank lines and whole-line // comments;
    # keep the line breaks (automatic semicolon insertion stays intact).
    lines = (line.strip() for line in s.split("\n"))
    return "\n".join(t for t in lines if t and not t.startswith("//"))


def minify_page(html):
    html = re.sub(r"<style>(.*?)</style>", lambda m: "<style>" + css_min(m.group(1)) + "</style>", html, flags=re.S)
    out = []
    for part in re.split(r"(<script>.*?</script>)", html, flags=re.S):
        if part.startswith("<script>"):
            out.append("<script>" + js_min(part[8:-9]) + "</script>")
        else:
            out.append(re.sub(r"\n[ \t]+", "\n", part))
    return "".join(out)


def bootstrap_url(source):
    body = re.sub(r"<!--.*?-->", "", source, flags=re.S)
    body = "".join(line.strip() for line in body.split("\n"))
    url = "data:text/html," + body
    bad = sorted({c for c in url if not ("!" <= c <= "~") or c in "#%"})
    if bad:
        sys.exit(f"bootstrap.html: characters that can't be typed into the address bar safely: {bad!r}")
    return url


US_SHIFTED = {'!': '1', '@': '2', '$': '4', '^': '6', '&': '7', '*': '8', '(': '9', ')': '0', '_': '-', '+': '=',
              '{': '[', '}': ']', '|': '\\', ':': ';', '"': "'", '~': '`', '<': ',', '>': '.', '?': '/'}
US_PLAIN = {'-': 0x2D, '=': 0x2E, '[': 0x2F, ']': 0x30, '\\': 0x31, ';': 0x33, "'": 0x34, '`': 0x35, ',': 0x36,
            '.': 0x37, '/': 0x38}


def us_key(c):
    """HID usage | 0x80 (Shift) for a printable ASCII character, US layout."""
    if "a" <= c <= "z":
        return 0x04 + ord(c) - ord("a")
    if "A" <= c <= "Z":
        return 0x80 | (0x04 + ord(c) - ord("A"))
    if "1" <= c <= "9":
        return 0x1E + ord(c) - ord("1")
    if c == "0":
        return 0x27
    if c in US_PLAIN:
        return US_PLAIN[c]
    if c in US_SHIFTED:
        return 0x80 | us_key(US_SHIFTED[c])
    raise ValueError(f"no US key for {c!r}")


def stream_reports(gz):
    """Reports deliver.c sends for the page: ',' + base32(len32 + gz) + '.' (+ a release
    between equal symbols, + the final release)."""
    data = len(gz).to_bytes(4, "big") + gz
    symbols = (len(data) * 8 + 4) // 5
    bits = int.from_bytes(data, "big") << (symbols * 5 - len(data) * 8)
    seq = [32] + [(bits >> (5 * (symbols - 1 - i))) & 31 for i in range(symbols)] + [33]
    repeats = sum(1 for a, b in zip(seq, seq[1:]) if a == b)
    return len(seq) + repeats + 1


def c_array(data, per_line=24):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) for i in range(0, len(data), per_line)]
    return "    " + ",\n    ".join(rows)


def artifacts():
    """(page, minified page, gzip bytes, bootstrap URL, bootstrap keys) - also used by tests."""
    page = (HERE / "sofle-config.html").read_text(encoding="utf-8")
    small = minify_page(page)
    gz = gzip.compress(small.encode("utf-8"), 9, mtime=0)
    url = bootstrap_url((HERE / "bootstrap.html").read_text(encoding="utf-8"))
    return page, small, gz, url, [us_key(c) for c in url]


def build():
    page, small, gz, url, keys = artifacts()
    boot_s = len(keys) * 2 * BOOT_REPORT_MS / 1000
    stream_s = stream_reports(gz) * STREAM_REPORT_MS / 1000
    source = hashlib.sha256((small + "\0" + url).encode("utf-8")).hexdigest()[:16]
    text = f"""// Generated by config_page/gen_page_blob.py from sofle-config.html and
// bootstrap.html - do not edit (rules.mk regenerates it at every build).
// Source {source}
//
// Page: {len(page)} bytes, minified {len(small)}, gzipped {len(gz)}.
// Typing time at full speed: address {boot_s:.1f} s, page {stream_s:.1f} s.

#pragma once

#include <stdint.h>

#define CONFIG_PAGE_GZ_LEN {len(gz)}
static const uint8_t config_page_gz[CONFIG_PAGE_GZ_LEN] = {{
{c_array(gz)}
}};

// The bootstrap data: URL as HID usages for a US layout; | 0x80 = with Shift.
#define CONFIG_BOOTSTRAP_LEN {len(keys)}
static const uint8_t config_bootstrap_keys[CONFIG_BOOTSTRAP_LEN] = {{
{c_array(keys)}
}};
"""
    return text, url, (len(page), len(small), len(gz), len(keys), boot_s, stream_s)


def main():
    text, url, (raw, small, gz, boot, boot_s, stream_s) = build()
    if "--print-url" in sys.argv:
        print(url)
        return
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    # gzip bytes differ between zlib versions: only rewrite when the source changed.
    same_source = re.search(r"// Source \w+", old) and re.search(r"// Source \w+", old).group(0) == re.search(r"// Source \w+", text).group(0)
    if same_source:
        text = old
    if old != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"config_page_blob.h: page {raw} -> {small} minified -> {gz} gzipped; bootstrap {boot} keys; "
          f"typing ~{boot_s:.0f} s + ~{stream_s:.0f} s{'' if old != text else ' (unchanged)'}", file=sys.stderr)


if __name__ == "__main__":
    main()
